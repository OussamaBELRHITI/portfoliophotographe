package com.portfolio.backend.entity;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import lombok.Getter;
import lombok.Setter;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.time.Instant;

/**
 * Fields every table in this schema needs: a surrogate primary key and audit timestamps.
 *
 * <p>{@code @MappedSuperclass} means this class is NOT a table of its own. Hibernate copies
 * these columns down into each subclass's table, so we get an {@code id}, {@code created_at}
 * and {@code updated_at} column on categories, media, site_settings and admin_users without
 * repeating the mapping each time.
 *
 * <p>The timestamps are filled in by Spring Data's {@link AuditingEntityListener}, which is
 * switched on by {@code @EnableJpaAuditing} in JpaAuditingConfig.
 */
@Getter
@Setter
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
public abstract class BaseEntity {

    /**
     * IDENTITY tells Hibernate the database generates the value — on Postgres this maps to a
     * BIGSERIAL / GENERATED BY DEFAULT AS IDENTITY column.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @CreatedDate
    @Column(nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(nullable = false)
    private Instant updatedAt;
}
